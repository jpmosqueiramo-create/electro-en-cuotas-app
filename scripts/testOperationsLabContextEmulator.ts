import './helpers/requireSafeEmulatorEnvironment';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { admin } from '../src/lib/firebaseAdmin';
import { createLabSession } from '../src/lib/operationsLabServer';
import { assertLabRecord, labRepository, labSessionReference, resolveLabExecutionContext } from '../src/lib/operationsLabContext';
import { reserveLabNumber } from '../src/lib/operationsLabNumbering';

async function main() {
  assert.equal(process.env.GCLOUD_PROJECT, 'demo-cuenta-hogar');
  assert.equal(process.env.FIRESTORE_EMULATOR_HOST, '127.0.0.1:8080');
  const db = admin.firestore(), uid = 'synthetic-context-admin', other = 'synthetic-context-other';
  const env = { OPERATIONS_LAB_ENABLED: 'true', OPERATIONS_LAB_ADMIN_UIDS: JSON.stringify([uid, other]) };
  const id = randomUUID();
  await createLabSession(db, uid, { commandId: id }, env);
  const context = await resolveLabExecutionContext(db, uid, id, env);
  const root = labSessionReference(db, uid, id);
  await assert.rejects(resolveLabExecutionContext(db, other, id, env));
  await assert.rejects(resolveLabExecutionContext(db, uid, '../foreign', env));
  assert.throws(() => labRepository({ ...context }));
  assert.throws(() => labRepository(JSON.parse(JSON.stringify(context))));
  const repo = labRepository(context);
  await assert.rejects(repo.read('solicitudes', 'normal'));
  await assert.rejects(repo.read('requests', '../normal'));
  await assert.rejects(repo.transaction(async tx => { tx.create('requests', 'reserved', { labContext: {} }); }));
  await assert.rejects(repo.transaction(async tx => {
    tx.create('requests', 'rollback', { synthetic: true });
    throw new Error('Synthetic transaction failure');
  }));
  assert.equal(await repo.read('requests', 'rollback'), null);
  await repo.transaction(async tx => { tx.create('requests', 'one', { synthetic: true }); });
  const record = await repo.read('requests', 'one');
  assertLabRecord(context, record);
  assert.throws(() => assertLabRecord(context, { ...record, labContext: { ...record!.labContext, sessionId: randomUUID() } }));
  assert.throws(() => assertLabRecord(context, { synthetic: true }));
  // Foreign/tampered envelopes fail at the persistence boundary, before domain use.
  await root.collection('requests').doc('foreign').create({ ...record, labContext: { ...record!.labContext, ownerUid: other } });
  await assert.rejects(repo.read('requests', 'foreign'));
  await assert.rejects(repo.transaction(tx => tx.read('requests', 'foreign')));
  const operationId = 'op_' + 'a'.repeat(64), commandId = randomUUID();
  const input = { commandId, operationId, snapshotHash: 'b'.repeat(64) };
  const beforeCH = await db.doc('contractNumberingV2/CONTRACT_NUMBERING_V1').get();
  const results = await Promise.all(Array.from({ length: 6 }, () => reserveLabNumber(context, input)));
  assert(results.every(r => JSON.stringify(r) === JSON.stringify(results[0])));
  assert.match(results[0].number, /^TEST-[a-f0-9]{64}-000001$/);
  const snap = root.collection('numberReservations').doc(operationId), before = await snap.get();
  await reserveLabNumber(context, input);
  assert((await snap.get()).updateTime!.isEqual(before.updateTime!));
  assert.equal((await root.collection('numberReservations').get()).size, 1);
  assert.equal((await root.collection('contracts').doc('numbering').get()).data()!.lastSequence, 1);
  await assert.rejects(repo.transaction(async tx => { tx.replace('numberReservations', operationId, { changed: true }); }));
  await assert.rejects(reserveLabNumber(context, { ...input, snapshotHash: 'c'.repeat(64) }));
  await assert.rejects(reserveLabNumber(context, { ...input, commandId: randomUUID() }));
  const second = randomUUID(); await createLabSession(db, uid, { commandId: second }, env);
  const otherContext = await resolveLabExecutionContext(db, uid, second, env);
  const otherNumber = await reserveLabNumber(otherContext, input);
  assert.notEqual(otherNumber.number, results[0].number);
  await createLabSession(db, other, { commandId: id }, env);
  const otherOwner = await resolveLabExecutionContext(db, other, id, env);
  assert.notEqual((await reserveLabNumber(otherOwner, input)).number, results[0].number);
  assert.throws(() => assertLabRecord(otherContext, record));
  const afterCH = await db.doc('contractNumberingV2/CONTRACT_NUMBERING_V1').get();
  assert.equal(afterCH.exists, beforeCH.exists);
  if (beforeCH.exists) assert(afterCH.updateTime!.isEqual(beforeCH.updateTime!));
  env.OPERATIONS_LAB_ENABLED = 'false';
  await assert.rejects(repo.read('requests', 'one'));
  env.OPERATIONS_LAB_ENABLED = 'true';
  await root.update({ disabledAt: new Date().toISOString() });
  await assert.rejects(repo.read('requests', 'one'));
  await assert.rejects(repo.transaction(async tx => { tx.create('requests', 'disabled', { synthetic: true }); }));
  assert.equal((await root.collection('requests').doc('disabled').get()).exists, false);
  console.log('LAB_CONTEXT_EMULATOR_PASS: capability forgery, owner/session isolation, scoped paths, provenance, rollback, concurrent reservation, immutable replay, TEST uniqueness, unchanged CH counter, live disablement');
}
main().then(() => admin.app().delete()).catch(error => { console.error(error.message); process.exitCode = 1; });
