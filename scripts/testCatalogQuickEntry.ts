import assert from 'node:assert/strict';
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { Timestamp } from 'firebase/firestore';
import { CatalogQuickEntry } from '../src/components/admin/catalog/CatalogQuickEntry';
import { catalogEntryMissing, nextCatalogEntry } from '../src/lib/catalogQuickEntry';
import { sameCatalogCreationValue } from '../src/lib/catalogReferenceCreate';
import { buildCatalogReferencePrivatePatch, createCatalogReferenceDraft } from '../src/lib/catalogReferenceEditor';

const initial = createCatalogReferenceDraft();
assert.deepEqual(catalogEntryMissing(initial), ['nombre', 'costo proveedor']);
assert.equal(Object.values(initial.planesActivos).some(Boolean), false, 'No automatic activation of terms.');
const draft = { ...initial, nombre: 'Producto uno', costoProveedor: '580000', proveedor: 'Proveedor de prueba', categoriaLogistica: 'C' as const, skuInterno: 'SKU-1', codigoBarras: '1234', descripcion: 'Descripción uno', imagenUrls: ['/logo-cuenta-hogar-oficial.png'], planesActivos: { ...initial.planesActivos, 12: true }, factoresPlanes: { ...initial.factoresPlanes, 12: 3.75 } };
assert.deepEqual(catalogEntryMissing(draft), []);
const next = nextCatalogEntry(draft);
for (const key of ['nombre', 'costoProveedor', 'skuInterno', 'codigoBarras', 'descripcion'] as const) assert.equal(next[key], '');
assert.deepEqual(next.imagenUrls, []);
assert.equal(next.proveedor, draft.proveedor); assert.equal(next.categoriaLogistica, 'C');
assert.equal(next.planesActivos[12], true); assert.equal(next.factoresPlanes[12], 3.75);
next.planesActivos[12] = false; next.factoresPlanes[12] = 1;
assert.equal(draft.planesActivos[12], true); assert.equal(draft.factoresPlanes[12], 3.75, 'No aliasing between products.');
const html = renderToStaticMarkup(createElement(CatalogQuickEntry, { draft, suppliers: ['Proveedor de prueba'], files: [], externalUrl: '', onChange: () => {}, onAdvanced: () => {}, onAddUrl: () => {}, onExternalUrlChange: () => {}, onAddFiles: () => {}, onRemoveFile: () => {} }));
assert.equal((html.match(/ required=""/g) ?? []).length, 2, 'Only name and cost are mandatory.');
assert.equal((html.match(/data-plan-row=/g) ?? []).length, 18);
assert(!html.includes('aria-label="Factor 12 cuotas"'), 'Factor controls stay in the complete editor.');
assert.match(html, /Fotos y descripción \(opcional\)/); assert.match(html, /1 plan seleccionado/);
const patch = buildCatalogReferencePrivatePatch(draft, { factoresPlanes: { 24: 4 }, precioContado: 777, stock: [{ id: 'legacy' }] });
assert.equal(patch.factoresPlanes['12'], 3.75); assert.equal(patch.factoresPlanes['24'], 4);
assert(!('stock' in patch)); assert(!('precioContado' in patch)); assert(!('publicado' in patch));
assert(sameCatalogCreationValue(Timestamp.fromMillis(1234), Timestamp.fromMillis(1234)));
assert(!sameCatalogCreationValue(Timestamp.fromMillis(1234), { seconds: 1, nanoseconds: 234000000 }));
assert(sameCatalogCreationValue({ a: [1, null], b: { x: true } }, { b: { x: true }, a: [1, null] }));
assert(!sameCatalogCreationValue({ a: 1 }, { a: 1, b: 2 }));
console.log('CATALOG_QUICK_REQUIRED_TWO_FIELDS_PLANS_NO_POLICY_CHANGE_REPEAT_CONFIGURATION_CLEAR_IDENTITY_TIMESTAMP_COMPARISON = PASS');
